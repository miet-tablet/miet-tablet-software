#pragma once

#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>

#include "stm32h7xx_hal.h"

#define GSL1680_I2C_ADDR (0x40U << 1) /* HAL expects an 8-bit shifted address */

typedef struct {
    uint8_t reg;
    uint32_t value;
} gsl1680_fw_entry_t;

typedef struct {
    uint16_t x;
    uint16_t y;
    uint8_t finger_id;
    uint8_t contacts;
    bool pressed;
} gsl1680_touch_t;

typedef struct {
    I2C_HandleTypeDef *i2c;
    GPIO_TypeDef *reset_port;  /* optional, NULL if reset is controlled externally */
    uint16_t reset_pin;
    bool ready;
} gsl1680_t;

/* Vendor panel-specific image: generated by tools/gsl1680_fw_convert.py. */
extern const gsl1680_fw_entry_t gsl1680_firmware[];
extern const size_t gsl1680_firmware_count;

/* Result: 0 OK; negative value is an error stage (see README). */
int gsl1680_init(gsl1680_t *dev, const gsl1680_fw_entry_t *fw, size_t fw_count);

/* Read first contact; 0 OK, negative on I2C/data error. */
int gsl1680_read(gsl1680_t *dev, gsl1680_touch_t *touch);
