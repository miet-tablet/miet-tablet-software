/**
 * @file    crc8.h
 * @brief   Модуль для подсчёта контрольной суммы CRC-8 (Dallas/Maxim)
 *
 * @details Нужен, чтобы проверять, что данные не испортились при
 *          передаче или хранении. Отправитель считает CRC от своих
 *          данных и добавляет её к ним, а мы на своей стороне считаем
 *          CRC заново и сравниваем. Если не совпало - данные битые
 *
 *          Параметры алгоритма CRC-8 Dallas/Maxim:
 *            - ширина:             8 бит;
 *            - полином:            x^8 + x^5 + x^4 + 1 (0x31);
 *            - начальное значение: 0x00;
 *            - порядок битов:      младшим вперёд (reflected), поэтому
 *                                  в коде стоит зеркальный полином 0x8C;
 *            - XOR на выходе:      0x00
 *
 * @note    Чтобы проверить модуль: CRC от строки "123456789"
 *          (без нуля в конце) должна выйти 0xA1
 */

#pragma once

#include <stdint.h>

/**
 * @brief   С этого значения начинается подсчёт CRC
 *
 * @details Если считаем CRC по кускам, то в первый вызов
 *          crc8_update() передаём именно его
 */
#define CRC8_INIT_VALUE 0x00

/**
 * @brief   Добавляет к текущей CRC один байт
 *
 * @details Пригодится, когда байты приходят по одному (например,
 *          из прерывания SPI) и складывать их в массив
 *          неохота.
 *          CRC тогда набирается постепенно:
 *
 * @code
 * uint8_t crc = CRC8_INIT_VALUE;
 * crc = crc8_update(crc, 0x02);
 * crc = crc8_update(crc, 0x1C);
 * @endcode
 *
 * @param[in] crc   Текущая CRC (для самого первого байта
 *                  передаём CRC8_INIT_VALUE)
 * @param[in] data  Новый байт данных
 *
 * @return  CRC с учётом нового байта
 */
uint8_t crc8_update(uint8_t crc, uint8_t data);

/**
 * @brief   Считает CRC-8 для массива байт
 *
 * @details Это просто обёртка над crc8_update(): проходит по всему
 *          массиву и возвращает итоговую сумму
 *
 * @code
 * uint8_t packet[] = {0x02, 0x1C, 0xB8, 0x01, 0x00, 0x00, 0x00};
 * uint8_t crc = crc8_calc(packet, sizeof(packet));  // выйдет 0xA2
 * @endcode
 *
 * @param[in] data    Указатель на массив с данными. Если там NULL,
 *                    вернётся CRC8_INIT_VALUE (считать-то нечего)
 * @param[in] length  Сколько байт из массива берём
 *
 * @return  CRC-8 для этих данных
 */
uint8_t crc8_calc(const uint8_t *data, uint32_t length);
